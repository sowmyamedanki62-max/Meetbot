from io import BytesIO

from docx import Document
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.shared import Inches, Pt, RGBColor


def create_meeting_document(
    title,
    meeting_date,
    user_name,
    minutes,
    transcript,
):
    document = Document()

    # Page layout
    section = document.sections[0]
    section.top_margin = Inches(0.7)
    section.bottom_margin = Inches(0.7)
    section.left_margin = Inches(0.8)
    section.right_margin = Inches(0.8)

    # Default font
    normal_style = document.styles["Normal"]
    normal_style.font.name = "Arial"
    normal_style.font.size = Pt(10)
    normal_style.font.color.rgb = RGBColor(48, 38, 83)

    # Main title
    heading = document.add_heading(
        "MeetBot Meeting Minutes",
        level=0,
    )
    heading.alignment = WD_ALIGN_PARAGRAPH.CENTER

    # Meeting details
    document.add_heading("Meeting Details", level=1)

    details = document.add_table(rows=0, cols=2)
    details.style = "Table Grid"

    for label, value in [
        ("Meeting Title", title),
        ("Meeting Date", meeting_date),
        ("Prepared By", user_name),
    ]:
        cells = details.add_row().cells
        cells[0].text = label
        cells[1].text = str(value)

    document.add_paragraph()
    document.add_heading("Meeting Minutes", level=1)

    # Convert common Markdown formatting to Word elements.
    minute_lines = minutes.splitlines()
    table_lines = []

    for line in minute_lines:
        stripped = line.strip()

        if not stripped:
            continue

        # Collect Markdown table lines for a Word table.
        if stripped.startswith("|"):
            table_lines.append(stripped)
            continue

        # Headings
        if stripped.startswith("### "):
            document.add_heading(stripped[4:], level=3)

        elif stripped.startswith("## "):
            document.add_heading(stripped[3:], level=2)

        elif stripped.startswith("# "):
            document.add_heading(stripped[2:], level=2)

        # Bullet points
        elif stripped.startswith("- ") or stripped.startswith("* "):
            paragraph = document.add_paragraph(style="List Bullet")
            paragraph.add_run(stripped[2:].replace("**", ""))

        # Numbered points
        elif (
            len(stripped) > 2
            and stripped[0].isdigit()
            and stripped[1:3] in (". ", ") ")
        ):
            paragraph = document.add_paragraph(style="List Number")
            paragraph.add_run(stripped[3:].replace("**", ""))

        else:
            document.add_paragraph(stripped.replace("**", ""))

    # Convert Markdown table rows into a Word table.
    if table_lines:
        parsed_rows = []

        for line in table_lines:
            cells = [
                cell.strip()
                for cell in line.strip("|").split("|")
            ]

            # Skip Markdown separator rows.
            if cells and all(
                not cell or set(cell) <= {"-", ":"}
                for cell in cells
            ):
                continue

            parsed_rows.append(cells)

        if parsed_rows:
            document.add_heading("Action Items Table", level=2)

            column_count = max(len(row) for row in parsed_rows)

            table = document.add_table(
                rows=0,
                cols=column_count,
            )
            table.style = "Table Grid"

            for row_index, row_data in enumerate(parsed_rows):
                cells = table.add_row().cells

                for column_index in range(column_count):
                    value = (
                        row_data[column_index]
                        if column_index < len(row_data)
                        else ""
                    )

                    cells[column_index].text = value.replace("**", "")

                    if row_index == 0:
                        for run in cells[column_index].paragraphs[0].runs:
                            run.bold = True
                            run.font.color.rgb = RGBColor(108, 76, 230)

    # Transcript on a separate page
    document.add_page_break()
    document.add_heading("Meeting Transcript", level=1)

    if transcript.strip():
        for paragraph_text in transcript.splitlines():
            if paragraph_text.strip():
                document.add_paragraph(paragraph_text.strip())
    else:
        document.add_paragraph("No transcript available.")

    # Footer
    for doc_section in document.sections:
        footer = doc_section.footer.paragraphs[0]
        footer.alignment = WD_ALIGN_PARAGRAPH.CENTER
        footer.add_run("Generated by MeetBot | Whisper + Ollama")

    # Return the Word document as downloadable bytes.
    output = BytesIO()
    document.save(output)
    output.seek(0)

    return output.getvalue()
